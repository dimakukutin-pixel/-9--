let questionIndex = 0;
const question = (prompt, options, answer) => {
  const shift = questionIndex++ % options.length;
  return {
    prompt,
    options: [...options.slice(shift), ...options.slice(0, shift)],
    answer: (answer - shift + options.length) % options.length
  };
};

